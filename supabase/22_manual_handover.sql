## 2. 넘겨줄 때 (그만두는 사람)

1. **전체 내보내기** 받기 — 데이터 업로드 → 📦 백업 받기 → **🗂 전체 내보내기** → 받은 zip을 **회사 드라이브 비공개 폴더**에 올리기
2. **기록 최신으로** — Claude에게 "**CLAUDE.md랑 README 최신으로 정리하고 main에 합쳐줘**"라고 하기. 아직 안 끝난 일은 CLAUDE.md의 '앞으로 할 일'에 남기기
3. **개인 계정에 묶인 것 정리**
   - 대시보드 '예약배송 상품 현황' 탭이 보여 주는 **구글 시트 '예약배송현황_발송 보류 건(FINCA&HaTA)'**가 **담당자 이름으로 된 회사 계정** 소유면, 그 사람이 나간 뒤 **계정이 삭제되면 시트도 같이 사라질 수 있어요.** → 나가기 전에 **소유자를 공용 계정(official@1inahundred.com)이나 새 담당자로 바꾸기**: 시트 → **공유** → 위 칸에 official@1inahundred.com 입력해 **편집자로 추가** → 그 줄 ▼ → **소유자로 지정** (공용 계정 메일로 온 요청을 **수락**해야 끝나요). 아래 '일반 액세스: one in a hundred'는 회사 전체 권한이라 소유자 지정이 안 돼요.
   - 소유자를 바꿔도 **시트 주소는 그대로**라 대시보드 연결은 끊기지 않아요
   - '전사플랜' 탭이 보여 주는 그로스본부 통합시트는 **그로스본부 시트**라 CX가 옮길 필요 없어요. 예전에 쓰던 '예약배송 자동정리' 시트는 **이제 안 써서** 옮기지 않아도 돼요
   - 개인 Claude 계정의 **예약 루틴**은 꺼져 있는지 확인 (넘기지 않음)
4. **VOC 리포트 자료 위치 알려주기** — VOC 리포트 스킬은 저장소 skills/ 폴더 + 회사 Claude 계정에 있음. **분석 코드 zip(FINCA_VOC리포트_분석코드.zip)은 회사 드라이브**에 있음 (고객 리뷰가 들어 있어 GitHub에 올리면 안 됨)
5. **같이 한 번 해 보기** — 새 담당자와 '📅 매일 데이터 올리기' 매뉴얼을 보면서 아침 루틴을 하루 같이 하기
6. **비밀번호 전달** → 나간 뒤에는 **공용 계정 비밀번호를 바꾸기** (권장)

