-- 31: 숫자 규칙 매뉴얼(id 6) — CS 데일리 해피톡 칸도 '업로드 데이터로 채우기'가 채움 (2026-10-28)
-- 노션 숫자 규칙 글은 같은 날 고침.

-- ① '직접 넣는 칸' 줄에서 해피톡 빼기
update manuals set body = regexp_replace(body, '(직접 넣는 칸[^\n]*?)\*\*해피톡\*\*, ', '\1')
where id = 6;

-- ② 그 줄 바로 아래에 해피톡 규칙 넣기 (두 번 실행해도 한 번만 들어가게)
update manuals set body = regexp_replace(body, '(\n[^\n]*직접 넣는 칸[^\n]*)',
  E'\\1\n- **해피톡 = 해피톡 분석에 넣은 상담(Aside 정리)으로 자동**이에요. (2026-10-28)\n  - **봇만 응대한 상담은 안 세요.** 진행 중이라도 상담원이 받은 건 세요.\n  - 고객 메시지 없이 접수만 된 상담 = **ONLY 접수**\n  - **불량·오배송 = 교환/반품 + VOC 상담** 둘 다에 들어가요. 재입고 문의는 상품문의로 세요.\n  - 그날 넣은 상담이 없으면 **손으로 넣은 값 그대로** 둬요.')
where id = 6 and body not like '%해피톡 분석에 넣은 상담%';

-- 확인: 1이 나오면 들어간 것
select id, (body like '%해피톡 분석에 넣은 상담%')::int as "해피톡 규칙" from manuals where id = 6;
