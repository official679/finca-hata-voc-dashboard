create table if not exists happytalk_items (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  brand text,                                   -- 핀카 / 하타
  platform text not null default '해피톡',      -- 업로드 공통 (중복 확인 키에 씀)
  source_key text not null,                     -- 상담일시 + 내용으로 만든 키 (같은 파일을 다시 올려도 중복 안 됨)
  written_at timestamptz,                       -- 상담 시각
  order_no text,
  ht_type text,                                 -- 배송 / 교환·반품 / 불량·오배송 / 취소·변경 / 상품문의 / 재입고 / 기타
  product_name text,
  product_id bigint,
  content text,                                 -- 고객이 원한 것
  answer text,                                  -- 우리 안내·처리 결과
  hint text,                                    -- 개선 힌트
  note text,
  unique (platform, source_key)
);
create index if not exists happytalk_items_written_idx on happytalk_items (written_at);

alter table happytalk_items enable row level security;
drop policy if exists "staff all" on happytalk_items;
create policy "staff all" on happytalk_items for all to authenticated using (true) with check (true);

select 'ok' as result, (select count(*) from happytalk_items) as happytalk_rows;
