## 2. 오후 품절 파일 (핀카 재고 맞추기)

> **받는 순서가 중요해요. 29CM은 맨 마지막.**
> 29CM 파일에는 '재고 버전'이 있어서, 받은 뒤 주문이 들어오면 업로드가 실패해요. 올리기 직전에 받을수록 실패가 적어요.

**① 오클릭 재고 RAW** (필수)
- 상품아소트/안전재고 (MY 폴더 즐겨찾기) · 브랜드 **FINCA** · 조회
- 위쪽 오른쪽 **엑셀 모양 버튼**

**② 오클릭 매칭검색어 — 바뀐 것만**
- 매칭검색어관리 · 판매처 **29CM**, **아임웹** 각각
- 변경일 = **지난번 받은 날 ~ 오늘** (담당 부서가 주말에도 고쳐요)
- 엑셀 → '상품 단위' 창은 **확인**
- 0건이면 안 넣어도 돼요
- **한 달에 한 번**은 전체를 받고 예전 매칭 파일은 지우기 (29CM은 많아서 변경일로 나눠 받기)

**③ 아임웹 (핀카만)**
- 쇼핑 → 상품 → **엑셀 다운로드**
- **'상품 정보 일괄 수정용'** 한 번 + **'옵션 정보 일괄 수정용'** 한 번 = 파일 2개
- ⚠️ 행사 전후엔 **올리기 직전에** 받기 (MD가 상품명을 바꾸면 업로드 오류)

**④ 무신사**
- 상품/재고 → **재고관리** · 상품상태 **판매중** · 브랜드 **핀카** · 검색
- **스크롤을 끝까지** 내리기 → 표에서 **오른쪽 클릭 → 내보내기**
- 나중에 붙여넣는 화면도 **똑같은 조건**(판매중 + 핀카)으로. 다르면 줄이 밀려요.

**⑤ 29CM (맨 마지막)**
- 상품 → **옵션/재고관리** → 상세검색
  - 프론트 브랜드 **핀카**
  - 옵션 판매 상태 **판매중 · 일시품절 · 판매중지** (판매종료는 빼기)
  - **300개씩** 보기
- **엑셀 다운로드 요청**: 페이지 **1-10 → 11-20 → …** 한 범위씩
- **다운로드 내역 창에서 '새로고침'** 을 눌러야 상태가 바뀌어요 → **'성공'** 뜨면 받기
  - 내역은 **최근 3개만** 보여요 → 하나 받고 다음 요청
- ✅ 다 받은 뒤 **파일 개수와 크기 확인** (11/4에 50개씩만 받아져서 재고 절반이 빠진 적 있음)

**⑥ (가끔) 오클릭 대체상품 목록** — 새로 등록했을 때만

→ 받은 파일을 **재고 맞추기 '넣을 파일' 폴더**에 넣고 계산·업로드 (📦 재고·발주 자동화 글)

