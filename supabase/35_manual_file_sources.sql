## 1. 아침 자료 (대시보드용)

### ① 주문 — 꼭 받기

**오클릭 (핀카 주문)**
- **언제**: 슬랙에 **'금일 발주 등록했습니다'가 3번** 올라온 뒤
- Seller → **주문검색/신규**
- 주문입력일 = **2일 전 ~ 오늘**, 판매처·배송창고 **전체** → 조회
- **엑셀저장 → 파일받기** (하타 줄이 섞여 있어도 업로드가 알아서 건너뜀)

**사방넷 (하타 주문)**
- **주문서확인처리**
- 일자 기준 **'주문일'** · **최근 7일** · 주문상태 **전체**
- 선택사항 거래처 = **HaTA[거래중]** ← **꼭!** 안 고르면 핀카까지 하타로 세어져요
- 검색 → **전체자료** + **CS 양식** → 엑셀
- 받은 뒤 **상품명이 전부 HaTA인지** 한 번 보기

