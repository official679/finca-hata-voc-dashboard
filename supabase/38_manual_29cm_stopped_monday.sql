update manuals
set body = replace(body,
      '옵션 판매 상태 **판매중 · 일시품절 · 판매중지** (판매종료는 빼기)',
      '옵션 판매 상태 **판매중 · 일시품절** (판매종료는 빼기)
  - **월요일만 판매중지도 같이** 체크 → ''판매중지인데 재고 있음'' 확인용 (매일 받으면 재고 맞추기가 6분 제한에 걸려요)'),
    updated_at = now()
where id = 10 and body like '%판매중 · 일시품절 · 판매중지** (판매종료는 빼기)%';

-- 확인: 아래가 1줄 나오면 성공
