update manuals
set body = $txt$## ✅ 먼저 메인의 '오늘 할 일'을 보세요

대시보드를 열면 **메인 맨 위 파란 띠 '✅ 오늘 할 일'**에 아침에 할 일이 **순서대로** 있어요.

- **파란 테두리 줄 = 지금 할 차례**예요. 그 줄을 누르면 **바로 그 화면으로** 가요.
- 끝난 일은 **번호 대신 ✓**로 바뀌어요. 위쪽 막대에 **몇 개 끝났는지**(예: 3/7 완료) 보여요.
- 오른쪽 **'접기 ▲'**를 누르면 **다음 할 일 한 줄만** 남아요. **'펼치기 ▼'**로 다시 열어요. (PC마다 기억해요)
- 위쪽에서 **핀카 / 하타**를 바꾸면 그 브랜드 기준으로 보여요.

| 순서 | 할 일 | 언제 ✓가 되나요 |
|---|---|---|
| ① | **파일 올리기** | 오늘 그 브랜드 **주문 파일**을 올리면 (리뷰·게시판은 ✓/– 로 표시만) |
| ② | **CS 데일리 저장** | 오늘 숫자를 **💾 저장**하면. 파일을 올린 뒤 누르면 **자동으로 채워진 채로** 열려요 |
| ③ | **데일리 리포트 슬랙 보고** | 리포트 창에서 **📋 이미지 복사**나 **⬇ PNG 저장**을 누르면 (그 PC에서만 ✓) |
| ④ | **예약배송 안내** | 안내할 주문이 **0건**이면 |
| ⑤ | **리뷰 체크필요** | VOC로 안 보낸 체크필요 리뷰가 **0건**이면 |
| ⑥ | **처리 대기 VOC** | 접수·확인중 VOC가 **0건**이면 |
| ⑦ | **데이터 백업** | 백업한 지 **30일이 지났을 때만** 나타나요 |

> **주말·공휴일**에는 ①~③이 흐리게 보여요 = **오늘은 안 해도 되는 일**이에요.

