create table if not exists voc_issues (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  brand text,                                   -- 핀카 / 하타
  title text not null,                          -- 예: 차렵이불 지퍼 불량 — 생산처 개선 요청
  kind text,                                    -- 품질 개선 요청 / 물류·바코드 점검 / 상세페이지 수정 (기준 관리 'issue_kind')
  status text not null default '요청',          -- 요청 / 진행중 / 완료 (모든 담당 부서가 완료하면 완료)
  depts jsonb not null default '[]'::jsonb,     -- [{ "dept": "생산팀", "done": "2026-10-20" }]  done 비어 있으면 아직
  log jsonb not null default '[]'::jsonb,       -- [{ "d": "2026-10-19", "dept": "CX", "text": "..." }]
  last_at date,                                 -- 마지막 기록 날짜 (⏰ 며칠째 계산용)
  done_at date
);
create index if not exists voc_issues_status_idx on voc_issues (status);

alter table voc_issues enable row level security;
drop policy if exists "staff all" on voc_issues;
create policy "staff all" on voc_issues for all to authenticated using (true) with check (true);

-- VOC ↔ 이슈 연결 (VOC 하나는 이슈 하나에만)
alter table voc_cases add column if not exists issue_id bigint references voc_issues(id) on delete set null;
create index if not exists voc_cases_issue_idx on voc_cases (issue_id);

-- 이슈 종류 (기준 관리에서 더할 수 있음)
insert into code_items (group_key, label, sort_order)
select v.g, v.l, v.s from (values ('issue_kind', '품질 개선 요청', 1), ('issue_kind', '물류·바코드 점검', 2), ('issue_kind', '상세페이지 수정', 3)) as v(g, l, s)
where not exists (select 1 from code_items c where c.group_key = v.g and c.label = v.l);

select 'ok' as result, (select count(*) from code_items where group_key = 'issue_kind') as issue_kinds;
