-- 32: 숫자 규칙 매뉴얼(id 6) — CS 데일리·데일리 리포트 부정 리뷰 = 리뷰 목록 체크 값 (2026-10-28)
-- 노션 숫자 규칙 글은 같은 날 고침.

update manuals set body = regexp_replace(body, '(\n[^\n]*나머지 = \*\*긍정\*\*[^\n]*)',
  E'\\1\n- **CS 데일리·데일리 리포트의 부정 리뷰 = 리뷰 목록의 체크 값**이에요. 사람이 긍정으로 바꾸면 부정에서 빠져요. 체크가 없으면 1~3점이에요. (2026-10-28)\n  - 이미 저장한 CS 데일리 숫자는 **그날 다시 채우기 → 저장**해야 바뀌어요.\n  - 리뷰 분석·회의록·보고서는 지금처럼 **별점**으로 세요.')
where id = 6 and body not like '%리뷰 목록의 체크 값%';

-- 확인: 1이 나오면 들어간 것 (0이면 알려 주세요 — 매뉴얼 문구가 달라서 못 찾은 것)
select id, (body like '%리뷰 목록의 체크 값%')::int as "부정 리뷰 규칙" from manuals where id = 6;
