update manuals
set body = replace(body, '카드의 파란 버튼을', '한 줄(**설치하기 ▸**)을 눌러 펼친 뒤 파란 버튼을'),
    updated_at = now()
where id = 2 and body like '%카드의 파란 버튼을%';

-- 확인: 아래가 1줄 나오면 성공
select id, title from manuals where id = 2 and body like '%설치하기 ▸%';
