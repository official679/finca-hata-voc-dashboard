  ('daily_platform:하타', '29CM', 1), ('daily_platform:하타', '아임웹', 2), ('daily_platform:하타', '무신사', 3),
  ('daily_platform:하타', 'W컨셉', 4), ('daily_platform:하타', 'EQL', 5)
on conflict (group_key, label) do nothing;

-- ---------------------------------------------------------------------
-- 4. 로그인한 직원만 접근
-- ---------------------------------------------------------------------
alter table cs_daily enable row level security;
alter table report_notes enable row level security;
drop policy if exists "staff all" on cs_daily;
drop policy if exists "staff all" on report_notes;
create policy "staff all" on cs_daily for all to authenticated using (true) with check (true);
create policy "staff all" on report_notes for all to authenticated using (true) with check (true);
