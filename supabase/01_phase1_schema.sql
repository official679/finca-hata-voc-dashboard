-- ---------------------------------------------------------------------
-- 4. 로그인한 직원만 읽기/쓰기 가능하도록 보안 설정
-- ---------------------------------------------------------------------
alter table code_items enable row level security;
alter table voc_cases enable row level security;
alter table cx_guides enable row level security;

drop policy if exists "staff all" on code_items;
drop policy if exists "staff all" on voc_cases;
drop policy if exists "staff all" on cx_guides;
create policy "staff all" on code_items for all to authenticated using (true) with check (true);
create policy "staff all" on voc_cases for all to authenticated using (true) with check (true);
create policy "staff all" on cx_guides for all to authenticated using (true) with check (true);

-- ---------------------------------------------------------------------
-- 5. VOC 사진 저장소 (비공개, 로그인한 직원만 접근)
-- ---------------------------------------------------------------------
insert into storage.buckets (id, name, public)
values ('voc-photos', 'voc-photos', false)
on conflict (id) do nothing;

drop policy if exists "staff read voc photos" on storage.objects;
drop policy if exists "staff upload voc photos" on storage.objects;
drop policy if exists "staff delete voc photos" on storage.objects;
create policy "staff read voc photos" on storage.objects for select to authenticated using (bucket_id = 'voc-photos');
create policy "staff upload voc photos" on storage.objects for insert to authenticated with check (bucket_id = 'voc-photos');
create policy "staff delete voc photos" on storage.objects for delete to authenticated using (bucket_id = 'voc-photos');
