-- ---------------------------------------------------------------------
-- 2. VOC 접수 (기존 'VOC 접수 대장' 시트)
-- ---------------------------------------------------------------------
create table if not exists voc_cases (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  received_date date not null default current_date,
  brand text not null,
  handler text,
  platform text,
  order_no text,
  orderer text,
  receiver text,
  product_id bigint references products(id),
  product_name text,
  voc_type text,
  consult_method text,
  status text not null default '접수',
  reason_category text,
  reason_detail text,
  note text,
  action_required text,
  action_done boolean not null default false,
  photos text[] not null default '{}'
);

create index if not exists voc_cases_received_date_idx on voc_cases (received_date);
create index if not exists voc_cases_product_id_idx on voc_cases (product_id);

